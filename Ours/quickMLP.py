import os
import sys
sys.path.insert(0, os.getcwd())
import yaml
import random
import argparse
from copy import deepcopy


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Process user defined hyperparameters')
    parser.add_argument('--dataset', type=str, help='The name of dataset.')
    parser.add_argument('--num_seeds', type=int, help='The number of random seeds generated by python.')
    parser.add_argument('--seeds_input', type=int, nargs='*', help='Your seeds input.')
    parser.add_argument('--annotation', help='Something we need to know about this experiment.')

    args = parser.parse_args()

    print(args)

    if args.dataset == 'VP':
        from Ours.hp import hp_quickMLP_virtual
        HpParams = hp_quickMLP_virtual
    elif args.dataset == 'RP':
        from Ours.hp import hp_quickMLP_real
        HpParams = hp_quickMLP_real

    if args.num_seeds:
        seeds = HpParams['seeds'] = random.sample(range(3225), k=args.num_seeds)
    else:
        seeds = HpParams['seeds'] = args.seeds_input

        name_exp = args.annotation
        HpParams['parent_dir'] = os.path.join(os.getcwd(), 'exps', args.dataset, name_exp)
        HpParams['annotation'] = args.annotation
        os.makedirs(HpParams['parent_dir'])       
    if HpParams['data_type'] == 'JA':
        from Ours.test import test_quickMLP
        from Ours.train import train_quickMLP
    elif HpParams['data_type'] == 'pos':
        from Ours.test_pos import test_quickMLP
        from Ours.train_pos import train_quickMLP
    for seed in seeds:
        HP_new = deepcopy(HpParams)
        HP_new.pop('seeds')
        HP_new['log_dir_path'] = os.path.join(HP_new['parent_dir'], str(seed))
        os.makedirs(os.path.join(HP_new['log_dir_path'], 'intermediate_files'))
        os.makedirs(os.path.join(HP_new['log_dir_path'], 'model_states'))
        HP_new['seed'] = seed
        with open(os.path.join(HP_new['log_dir_path'], 'parameters.yml'), 'w') as outfile:
            yaml.dump(HP_new, outfile, default_flow_style=False)

        for ps in HP_new['prediction_span']:
            train_quickMLP(HP_new, seed, ps)
            model_quickMLP = os.path.join(HP_new['log_dir_path'], 'model_states', f'best_quickMLP_{ps}.pth')
            test_quickMLP(HP_new, seed, model_quickMLP, ps)
    
    save_parent_HpDict = not os.path.isfile(os.path.join(HpParams['parent_dir'], 'parameters.yml'))
    if not (seed in HpParams['seeds']):
        HpParams['seeds'].append(seed)
        save_parent_HpDict = True
    if save_parent_HpDict:
        with open(os.path.join(HpParams['parent_dir'], 'parameters.yml'), 'w') as outfile:
            yaml.dump(HpParams, outfile, default_flow_style=False)