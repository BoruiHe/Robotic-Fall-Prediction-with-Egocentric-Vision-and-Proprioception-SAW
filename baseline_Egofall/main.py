import os
import sys
sys.path.insert(0, os.getcwd())
import yaml
import random
import argparse
import pickle as pk
from baseline_Egofall.test import test_Egofall_backbone, test_Egofall_clf
from baseline_Egofall.hp import hyperparameters_virtual, hyperparameters_real


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Process user defined hyperparameters')
    parser.add_argument('--dataset', type=str, help='The name of dataset.')
    parser.add_argument('--task_mode', type=str, default='all', choices=['ps', 're'], help='Select from \'ps\', \'re\'.')
    parser.add_argument('--num_seeds', type=int, help='The number of random seeds generated by python.')
    parser.add_argument('--seeds_input', type=int, nargs='*', help='Your seeds input.')
    parser.add_argument('--name_exp', type=str, help='Path to the target folder of experiment. Use this only when you need to test models.')
    parser.add_argument('--annotation', help='Something we need to know about this experiment.')

    args = parser.parse_args()
    # args = parser.parse_args('--dataset VP --task_mode ps --seeds_input 608 --annotation Egofall_debug'.split())
    # args = parser.parse_args('--dataset RP  --num_seeds 5 --annotation $(annotation)'.split())
    # args = parser.parse_args('--seeds_input 608  -name_exp /home/bhe100/SAW/exps/$(dataset)/$(annotation)'.split())
    
    print(args)

    if args.name_exp:
        with open(os.path.join(args.name_exp, 'parameters.yml')) as f:
            HpParams = yaml.safe_load(f)
        if args.num_seeds:
            seeds = random.sample(range(3225), k=args.num_seeds)
        else:
            seeds = args.seeds_input
        assert len(seeds) > 0, 'Empty seeds input.'
        with open(os.path.join(HpParams['parent_dir'], 'score.pkl'), 'rb') as f:
            score = pk.load(f)
    else:
        if args.dataset == 'VP':
            HpParams = hyperparameters_virtual
        elif args.dataset == 'RP':
            HpParams = hyperparameters_real
        HpParams['seeds'] = []
        if args.num_seeds:
            seeds = random.sample(range(3225), k=args.num_seeds)
        else:
            seeds = args.seeds_input

        HpParams['parent_dir'] = os.path.join(os.getcwd(), 'exps', args.dataset, args.annotation)
        HpParams['annotation'] = args.annotation

        score = {}
        
    for seed in seeds:        
        # if we have a new seed
        if not seed in HpParams['seeds']:
            score[seed] = {
                'iter': [],
                'flat': [],
            }
            os.makedirs(os.path.join(HpParams['parent_dir'], str(seed)))
            if args.task_mode == 'ps':
                for ps in HpParams['prediction_span']:
                    test_Egofall_backbone(HpParams, seed, args.task_mode, ps)
                    # test_Egofall_clf(HpParams, score, seed, args.task_mode, ps)
            else:
                test_Egofall_backbone(HpParams, seed, args.task_mode)
                # test_Egofall_clf(HpParams, score, seed, args.task_mode)
            HpParams['seeds'].append(seed)
            
    with open(os.path.join(HpParams['parent_dir'], 'score.pkl'), 'wb') as f:
        pk.dump(score, f)   
    with open(os.path.join(HpParams['parent_dir'], 'parameters.yml'), 'w') as outfile:
        yaml.dump(HpParams, outfile, default_flow_style=False)

